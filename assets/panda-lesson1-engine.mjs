 if(/你好/u.test(raw)&&/(?:произн|тон|звуч|чита|почему|меня|разниц|словарн)/u.test(low))return FACTS['你好'];
 if(/(?:тон|произн)/u.test(low)){
  for(const key of ['学生','我','你','是','好'])if(raw.includes(key))return FACTS[key];
  return 'Напиши слово из урока 1: 我, 你, 是, 学生 или 你好. Объясню его тоны.';
 }
 if(/(?:порядок слов|собрать предложение|я студент|я ученик|как сказать|перевести)/u.test(low)&&/(?:студент|ученик|我是学生)/u.test(raw))return FACTS['我是学生'];
 for(const key of ['我是学生','学生','你好','我','你','是','好']){
  if(norm===key||(raw.includes(key)&&/(?:знач|перевод|чита|произн|почему|что такое|как по|тон)/u.test(low)))return FACTS[key];
 }
 if(/(?:что такое черта|порядок черт|как пиш)/u.test(low))return 'Черта — отдельное движение при письме. У 好 шесть черт; анимацию порядка черт можно посмотреть в первом уроке.';
 return '🐼 В бесплатном режиме я отвечаю только по уроку 1: 好, 我, 你, 是, 学生, 你好, четыре тона, черты и предложение 我是学生. Выбери готовую тему или спроси об одном из этих слов.';
