export function normalizeAnswer(value){
 return String(value??'').normalize('NFC').toLowerCase().trim().replace(/[\s。、！!？，?.,;；:："'«»()\-–—]/g,'').replace(/ё/g,'е');
}
export function grade(task,answer,attempt=1){
 if(!task||!Array.isArray(task.answers))return {ok:false,text:'Такого задания нет.'};
 const input=normalizeAnswer(answer);
 if(!input)return {ok:false,text:'Напиши свой ответ.'};
 if(task.answers.some(x=>normalizeAnswer(x)===input))return {ok:true,text:'✅ Верно! '+task.correct};
 return {ok:false,text:'Пока неправильно. '+(attempt>=2?'Подсказка: '+task.hint:'Попробуй снова. Подсказка будет после второй попытки.')};
}
