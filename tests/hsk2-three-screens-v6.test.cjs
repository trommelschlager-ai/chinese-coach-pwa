'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM,VirtualConsole}=require('jsdom');
const root=path.resolve(__dirname,'..');
const bastian=fs.readFileSync(path.join(root,'hsk2-bastian-intro.html'),'utf8');
const map=fs.readFileSync(path.join(root,'hsk2-start.html'),'utf8');
const poster=fs.readFileSync(path.join(root,'assets/bastian-three-screens-v6.css'),'utf8');
const plan=fs.readFileSync(path.join(root,'assets/hsk2-one-screen-map-v6.css'),'utf8');
assert.match(bastian,/bastian-approved-reference-v5\.jpg/,'Must retain untouched approved screenshot');
assert.match(bastian,/bastian-three-screens-v6\.css/,'Full-height and audio layout stylesheet must load');
assert.match(map,/hsk2-one-screen-map-v6\.css/,'HSK2 map compact stylesheet must load');
assert.match(poster,/#poster:not\(\[hidden\]\)\{[\s\S]*?height:100dvh!important/,'Poster viewport must use the device height');
assert.match(poster,/aspect-ratio:864\/1536!important/,'Poster must preserve approved aspect ratio');
assert.match(poster,/object-fit:contain!important/,'Image and hotspots must retain natural proportions');
assert.doesNotMatch(poster,/object-fit:fill!important/,'Never stretch approved Bastian artwork');
assert.match(poster,/\.word-grid\{[\s\S]*?repeat\(2,minmax\(0,1fr\)\)/,'Audio words must have two columns');
assert.match(poster,/grid-template-rows:repeat\(5,minmax\(0,1fr\)\)/,'Audio words must have five rows');
assert.match(plan,/\.journey-road\{[\s\S]*?repeat\(2,minmax\(0,1fr\)\)/,'Course plan must have two columns');
assert.match(plan,/grid-template-rows:repeat\(5,minmax\(0,1fr\)\)/,'Course plan must have five rows');
const errorList=[];
const vc=new VirtualConsole();
vc.on('jsdomError',e=>errorList.push(e.message));
const dom=new JSDOM(bastian,{
 url:'https://example.test/hsk2-bastian-intro.html',runScripts:'dangerously',virtualConsole:vc,
 beforeParse(w){w.scrollTo=()=>{};}
});
const doc=dom.window.document;
const $=sel=>doc.querySelector(sel);
const click=sel=>{const el=$(sel);assert.ok(el,'Missing '+sel);el.click()};
assert.equal($('#poster').hidden,false);
click('#start');
assert.equal($('#poster').hidden,true);
assert.equal($('#practice').classList.contains('word-stage'),true);
const grid=$('#step-content .word-grid');
assert.ok(grid,'Words have compact grid wrapper');
assert.equal(grid.querySelectorAll('.word').length,10);
assert.equal(grid.querySelectorAll('button.play').length,10,'Each word must have its audio control');
assert.equal(grid.querySelectorAll('.hz').length,10);
click('#next');
assert.equal($('#practice').classList.contains('word-stage'),false,'Other teaching stages must scroll normally');
click('#prev');
assert.equal($('#practice').classList.contains('word-stage'),true);
click('#prev');
assert.equal($('#poster').hidden,false);
assert.deepEqual(errorList,[],'No browser-side script errors');
const journeyStart=map.indexOf('const JOURNEY=[');
const journeyEnd=map.indexOf('];',journeyStart);
assert.ok(journeyStart>=0&&journeyEnd>journeyStart,'Course topic registry must exist');
assert.equal((map.slice(journeyStart,journeyEnd).match(/^\s*\['/gm)||[]).length,10,'Show all ten course topics');
console.log('PASS: three mobile screens · full-height Bastian artwork, 10-word audio grid, 10-topic course plan, stage navigation');
