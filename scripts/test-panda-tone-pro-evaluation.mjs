import assert from 'node:assert/strict';
import {evaluate} from './evaluate-panda-tone-pro.mjs';
const frames=(fn,n=25)=>Array.from({length:n},(_,i)=>({t:i*.016,hz:160*2**(fn(i/(n-1))/12),clarity:.95}));
const speaker={id:'held',split:'held-out',calibrationFrames:frames(x=>-5+10*x,100)};
const row=(id,acceptable,f)=>({id,speakerId:'held',wordId:'brush',syllableIndex:1,reviewersAgree:true,verifiedBoundaries:true,lexicalMatch:true,acceptable,frames:f});
const rise=frames(x=>-4+8*x),fall=frames(x=>4-9*x);
const data={speakers:[speaker,{...speaker,id:'dev',split:'development'}],cases:[row('a',true,rise),row('b',false,fall),row('c',false,rise),row('d',true,fall),row('e',true,[]),row('f',false,[]),{...row('g',true,rise),speakerId:'dev'}]};
const r=evaluate(data);
assert.equal(r.counts.total,6);
assert.equal(r.coverage,4/6);
assert.equal(r.accuracyAmongGraded,.5);
assert.equal(r.falseAcceptance,1/3);
assert.equal(r.falseRejection,1/3);
assert.equal(r.counts.abstainedCorrect,1);
assert.equal(r.counts.abstainedIncorrect,1);
assert.equal(r.heldOutSpeakers,1);
assert.equal(r.releaseApproved,false);
assert.equal(evaluate({speakers:[],cases:[]}).coverage,null);
assert.throws(()=>evaluate({...data,cases:[data.cases[0],data.cases[0]]}));
assert.throws(()=>evaluate({...data,cases:[{...data.cases[0],reviewersAgree:false}]}));
console.log('PASS evaluator synthetic accounting; no human accuracy claim');
