d.getElementById('focus-known').click();assert.equal(w.location.hash,'#course/3/1/1');
assert.equal(JSON.parse(w.localStorage.getItem('chinese-coach-review-v1'))['我'].level,1,'Schedule the word actually recalled');
w.openCourseLesson(3,1,0);d.querySelector('.recall-practice').open=true;await tick();d.getElementById('recall-reveal').click();d.getElementById('recall-again').click();
assert.equal(JSON.parse(w.localStorage.getItem('chinese-coach-review-v1'))['我'].level,0);
assert(!JSON.parse(w.localStorage.getItem('chinese-coach-personal-v1')).learned.includes('我'));
d.getElementById('course-topics-back').click();assert.equal(w.location.hash,'#topics/words','Words returns to word topics');
w.openLearningTopics('dialogues');
assert(d.querySelector('[data-dialog-lesson="2"]'),'Conversation topic is visible independently');
d.querySelector('[data-dialog-lesson="2"]').click();
assert.equal(d.querySelectorAll('#topics .clean-dialog-line').length,6,'All conversation turns shown with no tones');
w.openCourseLesson(2,2,0);
assert.equal(d.querySelectorAll('.dialogue-row').length,6,'All dialogue turns remain visible');
for(let n=0;n<3;n++)d.getElementById('course-next').click();
assert.equal(w.location.hash,'#course/2/2/3');
assert.equal(d.querySelectorAll('.current-line').length,1);
assert.equal([...d.querySelectorAll('.dialogue-row')].findIndex(row=>row.classList.contains('current-line')),3,'Fourth dialogue turn stays selected');
