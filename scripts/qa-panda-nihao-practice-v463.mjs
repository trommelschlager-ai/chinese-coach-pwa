import assert from 'node:assert/strict';
import fs from 'node:fs';
import {chromium} from 'playwright';
const base=process.env.PANDA_TEST_BASE||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
try{
 const context=await browser.newContext({viewport:{width:393,height:852},deviceScaleFactor:1,isMobile:true,hasTouch:true,locale:'ru-RU',permissions:['microphone','clipboard-read','clipboard-write']});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('requestfailed',r=>errors.push(r.url()+' '+(r.failure()?.errorText||'')));
 await page.goto(base+'/panda-nihao-practice.html',{waitUntil:'networkidle',timeout:30000});
 assert.match(await page.locator('.hanzi').innerText(),/你好/);
 assert.equal(await page.locator('.stage').count(),3);
 assert.match(await page.locator('.rule').innerText(),/3 \+ 3 → 2 \+ 3/);
 await page.locator('#listen').click();
 await page.locator('#audio-status').filter({hasText:/Воспроизвожу|Chrome/}).waitFor({timeout:10000});
 await page.locator('.stage[data-stage="1"]').click();
 assert.match(await page.locator('#tip').innerText(),/третий тон/);
 assert.equal(await page.locator('.stage[data-stage="1"]').getAttribute('aria-pressed'),'true');
 await page.locator('#record').click();
 await page.locator('#status').filter({hasText:/Микрофон включён/}).waitFor({timeout:10000});
 assert.equal(await page.locator('#stop').isDisabled(),false);
 await page.waitForTimeout(1200);
 await page.locator('#stop').click();
 await page.locator('#status').filter({hasText:/Готово/}).waitFor({timeout:10000});
 assert.equal(await page.locator('#record').isDisabled(),false);
 await page.locator('#playback').waitFor({state:'visible',timeout:12000});
 await page.locator('.stage[data-stage="2"]').click();
 assert.equal(await page.locator('#playback').isVisible(),false,'Old raw recording should be discarded when switching stage');
 assert.match(await page.locator('#step-pinyin').innerText(),/ní hǎo/);
 await page.locator('#record').click();
 await page.locator('#status').filter({hasText:/Микрофон включён/}).waitFor({timeout:10000});
 await page.waitForTimeout(900);
 await page.locator('#stop').click();
 await page.locator('#feedback').filter({hasText:/не разделяет слоги|график скрыт/}).waitFor({timeout:12000});
 assert.equal(await page.locator('#copy-data').isDisabled(),false);
 fs.mkdirSync('qa/panda-nihao',{recursive:true});
 await page.screenshot({path:'qa/panda-nihao/android-393x852.png',fullPage:true});
 assert.deepEqual(errors,[],'No script crashes or failed network loads');
 console.log('PASS: 你好 user training, approved reference sample, T2/T3 sandhi, own mic recording, whole phrase without fake grade, Android viewport 393x852');
 await context.close();
}finally{await browser.close()}
