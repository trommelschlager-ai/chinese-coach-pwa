assert.equal(bar.getAttribute('aria-valuemax'),'7');
assert.equal(bar.getAttribute('aria-valuenow'),'0');
assert(js.includes("setAttribute('aria-valuenow',String(state.completed?7:state.step))"));
assert(js.includes("setAttribute('aria-valuetext','Пройдено '"));
assert(css.includes("/* v170:"),"Mobile polish styles missing");
assert(css.includes(".lesson-step:not(:disabled):active"),"Press feedback must apply to lesson step buttons");
assert(css.includes(".lesson-controls button:not(:disabled):active"),"Press feedback must apply to footer navigation");
assert(css.includes(".lesson-audio:not(:disabled):active"),"Press feedback must apply to audio buttons");
assert(css.includes(".lesson-line > div:nth-child(2){min-width:0}"),"Dialogue overflow protection missing");
assert(css.includes(".lesson-line .lesson-hanzi"),"Mandarin line should remain readable on narrow Android screens");
