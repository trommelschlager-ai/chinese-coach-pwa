'use strict';
/* v170 HSK 1 visual polish: preserve artwork, audio and seven-step structure. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const page=fs.readFileSync('hsk1-lesson.html','utf8');
const css=fs.readFileSync('assets/hsk1-foundations-v152.css','utf8');
const js=fs.readFileSync('assets/hsk1-foundations-v152.js','utf8');
const journey=fs.readFileSync('assets/hsk1-journey-approved-v176.css','utf8');
