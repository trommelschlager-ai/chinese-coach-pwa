/* Approved travel visual redesign — focused nonregression checks. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('travel.html','utf8');
const css=fs.readFileSync('assets/travel-wow-v1.css','utf8');
assert(html.includes('assets/travel-wow-v1.css?v=1'),'New map stylesheet must be loaded');
assert(!html.includes('Панда ждёт тебя!'),'Remove redundant panda waiting banner');
const dom=new JSDOM(html);
const d=dom.window.document;
assert.equal(d.querySelectorAll('#travel-map .stop').length,4,'Four travel stops preserved');
assert(d.getElementById('airport-status'),'Progress status preserved');
assert(d.getElementById('map-badge'),'Map progress badge preserved');
assert.equal(d.querySelectorAll('[data-start]').length,2,'Original map and start actions preserved');
assert(d.getElementById('check-answer')&&d.getElementById('reward-screen'),'Quiz and reward preserved');
assert(d.querySelector('#travel-map .travel-map-panda[src="./assets/game-panda-v80.webp"]'),'Use existing panda art');
assert.equal(d.querySelectorAll('#travel-map .travel-spark').length,3,'Three subtle route sparks');
assert.equal(d.querySelectorAll('#travel-map .route path.route-dashes').length,1,'One moving dashed route');
assert.equal(d.querySelectorAll('#travel-map .route path.route-light').length,1,'One highlighted route');
const motion=d.querySelector('#travel-map .route-runner animateMotion');
assert(motion&&motion.getAttribute('dur')==='9s','Moving route sparkle is animated');
assert(d.querySelector('#travel-map .route-runner mpath[href="#travel-route-shape"]'),'Light follows real path');
const routePaths=['route-track','route-light','route-dashes'].map(cls=>d.querySelector('#travel-map .route path.'+cls)?.getAttribute('d'));
assert(routePaths.every(x=>x===routePaths[0]),'Light and track must align perfectly');
assert(css.includes('@keyframes travel-route-flow'),'Dashes must move along route');
assert(css.includes('@media(prefers-reduced-motion:reduce)'),'Reduced motion accessibility required');
assert(css.includes('.route-runner{display:none}'),'Decorative moving light disabled for reduced motion');
assert(css.includes('.travel-voice .voice-task'),'Approved voice lesson also styled');
assert(!css.includes('body{'),'New visual CSS must not globally restyle existing application');
dom.window.close();
console.log('Travel WOW checks passed: approved moving path, no redundant banner, existing lesson and voice untouched.');
