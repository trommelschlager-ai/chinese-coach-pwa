'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const s=fs.readFileSync(path.join(root,'hsk2-start.html'),'utf8');
