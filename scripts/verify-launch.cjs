// Focused regression: the approved cover is still and only the Start action launches petals.
// Six menu choices are available; choice six navigates to the separate writing trainer.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
assert(html.includes('src="./assets/approved-home-v36.png"'),'Approved welcome cover source must be kept');
assert(html.includes('src="./assets/approved-lessons.png"'),'Approved five-card menu image must be kept');
assert(fs.existsSync('hanzi-lab.html'),'Hanzi writing trainer must exist');
assert(!html.includes("if(what==='cover')startPetals()"),'Cover should not create petals on entry');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(Boolean);
const launch=scripts.find(s=>s.includes("const root=document.getElementById('launch-entry')"));
assert(launch,'Launch controller script is present');
const dom=new JSDOM(html,{url:'https://example.test/chinese-coach-pwa/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
let opened=0;
w.matchMedia=()=>({matches:false,addListener(){}});
w.scrollTo=()=>{};
w.go=()=>{};
w.openCourseLesson=()=>{opened++};
w.eval(launch);
const root=d.getElementById('launch-entry');
const cover=d.getElementById('launch-cover');
const menu=d.getElementById('launch-menu');
const sixth=d.getElementById('launch-hanzi');
assert(root&&!root.hidden,'Welcome overlay is visible');
assert(!cover.hidden&&menu.hidden,'Approved cover must be the first screen');
assert(!root.classList.contains('petals-falling')&&!root.classList.contains('launch-sakura'),'No falling petals on first launch');
assert.equal(root.querySelectorAll('#launch-petals .sakura-petal').length,190,'Petal elements preloaded but inactive');
assert.equal(menu.querySelectorAll('[data-choice]').length,5,'Existing five lesson choices preserved');
assert(sixth&&sixth.tagName==='A','New sixth item must be a real link');
assert.equal(sixth.getAttribute('href'),'./hanzi-lab.html','Sixth option points to writing lesson');
assert.equal(sixth.querySelector('.hanzi-sixth-icon').textContent.trim(),'6','New option marked as sixth');
assert(sixth.textContent.includes('Написание иероглифов'),'Visible label names the writing trainer');
assert.equal(sixth.parentElement,menu,'Sixth option belongs to lessons screen');
assert(!d.querySelector('#launch-cover #launch-hanzi'),'Welcome artwork remains unchanged');
d.getElementById('launch-start').click();
assert(root.classList.contains('petals-falling')&&root.classList.contains('launch-sakura'),'Only clicking Start triggers falling petals');
d.getElementById('launch-back').click();
assert(!root.classList.contains('petals-falling')&&!root.classList.contains('launch-sakura'),'Returning to cover must not replay petals');
assert(!cover.hidden&&menu.hidden,'Back returns to original welcome cover');
d.getElementById('launch-start').click();
assert(root.classList.contains('petals-falling'),'A new explicit Start tap can replay petals');
d.getElementById('launch-all').click();
assert(root.hidden,'Opening existing lessons closes overlay');
assert.equal(opened,1,'Original lesson selection remains functional');
assert(!root.classList.contains('petals-falling'),'Exiting overlay cancels petal animation');
console.log('Launch checks passed: still cover, single tap-triggered petals, five preserved choices, sixth Hanzi link.');
dom.window.close();
