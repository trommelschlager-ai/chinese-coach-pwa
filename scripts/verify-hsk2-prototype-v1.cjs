'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const lesson=fs.readFileSync(path.join(root,'hsk2-lesson1.html'),'utf8');
const map=fs.readFileSync(path.join(root,'hsk2-map.html'),'utf8');
const match=lesson.match(/<script type="application\/json" id="lesson-data">([\s\S]*?)<\/script>/);
assert(match,'HSK 2 data missing');
const data=JSON.parse(match[1]);
assert.equal(data.vocabulary.length,12);
assert.equal(data.dialogue.length,4);
assert(data.vocabulary.map(w=>w.hanzi).includes('中文'));
assert(data.vocabulary.map(w=>w.hanzi).includes('忙'));
assert(data.vocabulary.map(w=>w.hanzi).includes('用'));
for(const e of [...data.vocabulary,...data.examples,...data.dialogue])assert(e.hanzi&&e.pinyin&&e.ru);
assert(lesson.indexOf("kind:'words'")<lesson.indexOf("kind:'rule-svo'"),'Words must precede grammar');
assert(lesson.indexOf("kind:'quiz'")<lesson.indexOf("kind:'rule-svo'"),'Vocabulary quiz must precede grammar');
assert(lesson.includes('localStorage.setItem(key'),'Progress missing');
assert(lesson.includes('hidden-pinyin'),'Pinyin toggle missing');
assert(lesson.includes("kind:'build'"),'Sentence builder missing');
assert(lesson.includes('pg-hsk2-foundation-v3-progress'),'Lesson progress must not reuse old ID');
assert(map.includes('href="./hsk2-lesson1.html"'));
assert(map.includes('Слова → предложения'));
assert(map.includes('СКОРО'));
assert(!map.includes('Мои увлечения'));
const scripts=[...lesson.matchAll(/<script(?: [^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(x=>x.includes('(()=>{'));
assert.equal(scripts.length,1);
for(const s of scripts)new vm.Script(s);
console.log('HSK2 v3 words first: vocabulary, lesson order, sentence builder, map and JS syntax passed');
