/* Approved Panda Go v3: navigation and sakura regression verification. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('assets/menu-v3-approved.css','utf8');
const js=fs.readFileSync('assets/menu-v3-approved.js','utf8');
const art=fs.readFileSync('assets/menu-v3-approved.webp');
assert(art.length>40000&&art.length<300000,'Approved image asset must be optimized for Android');
assert.equal(art.toString('ascii',0,4),'RIFF');
assert.equal(art.toString('ascii',8,12),'WEBP');
assert(html.includes('menu-v3-approved.css?v=1')&&html.includes('menu-v3-approved.js?v=1'));
assert(css.includes('prefers-reduced-motion:reduce'),'Respect OS reduced-motion setting');
assert(css.includes('pointer-events:none!important'),'Petals never steal taps');
assert(css.includes('infinite both'),'Petals always fall');
const dom=new JSDOM(html,{url:'https://example.test/chinese-coach-pwa/',runScripts:'outside-only'});
const w=dom.window,d=w.document;
w.courseProgress={readGame:()=>({streak:5,points:320})};
let chosen=-1;
d.querySelectorAll('#launch-menu [data-choice]').forEach(b=>b.addEventListener('click',()=>{chosen=Number(b.dataset.choice)}));
let back=0,started=0;
d.querySelector('#launch-back').addEventListener('click',()=>{back++});
const start=d.createElement('button');start.className='daily-start';start.onclick=()=>started++;d.querySelector('.six-screen-content').append(start);
w.eval(js);
const menu=d.getElementById('launch-menu');
assert(menu.classList.contains('panda-v3-active'),'Approved layout activated');
assert.equal(menu.querySelectorAll('.panda-v3-petal').length,16,'Sixteen diverse falling petals');
assert.equal(menu.querySelectorAll('.panda-v3-hit').length,5,'Five real navigation hits');
assert.equal(menu.querySelector('.panda-v3-live-stats').textContent.includes('320'),true,'Live progress');
assert.equal(menu.querySelectorAll('.six-menu-cards [data-choice]').length,7,'Old seven direct categories preserved');
assert(menu.querySelector('.six-menu-cards .six-travel'),'Travel link preserved');
function click(action){menu.querySelector('[data-v3-action="'+action+'"]').click()}
click('learn');assert(!menu.querySelector('.panda-v3-overlay').hidden);
assert.equal(menu.querySelectorAll('[data-v3-links] button').length,4);
menu.querySelectorAll('[data-v3-links] button')[1].click();assert.equal(chosen,1,'Words remain available');
click('practice');assert.equal(menu.querySelectorAll('[data-v3-links] button').length,3);
menu.querySelectorAll('[data-v3-links] button')[2].click();assert.equal(chosen,6,'Game remains available');
click('start');assert.equal(started,1,'Existing daily practice remains connected');
click('back');assert.equal(back,1,'Old cover navigation preserved');
assert(menu.querySelector('.panda-v3-lesson-meter'), 'Daily progress meter stays visible');
w.close();
console.log('v127 Panda Go approved menu: optimized art, 16 animated petals, existing study/practice/travel and live stats verified.');
